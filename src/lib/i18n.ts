export function formatNumber(num: number): string {
  return Math.round(num)
    .toString()
    .replace(/\B(?=(\d{3})+(?!\d))/g, ' ');
}

export function formatPrice(num: number, lang: Language): string {
  return `${formatNumber(num)} ${translations[lang].product.currency}`;
}

export function l(lang: Language, uz: string, ru: string): string {
  return lang === 'ru' ? ru || uz : uz || ru;
}

export function interpolate(template: string, vars: Record<string, string | number>): string {
  return Object.entries(vars).reduce(
    (acc, [key, value]) => acc.replaceAll(`{{${key}}}`, String(value)),
    template
  );
}

